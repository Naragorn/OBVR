#!/usr/bin/env python3
"""Writes tools/hand-scripts/swim-arms.txt: the player in Lake Rumare, the scripted hands stroking.

The hand script's hands move only at a command, and a scripted hand's speed is its way since the
last frame over the frame's time (docs/hand-script-harness.md), so a stroke is written in steps of
a few milliseconds, finer than any frame: the speed the game reads is the stroke's own at any
frame rate.

  python3 tools/gen-swim-script.py            > tools/hand-scripts/swim-arms.txt
  python3 tools/gen-swim-script.py --film     > swim-arms-film.txt   (head down, hands in the picture)
"""
import sys

STEP = 0.004          # seconds between two hand commands
PULL_SECONDS = 0.45   # a stroke's pull
PULL_METRES = 0.60    # and its length: 1.33 m/s
RECOVER_SECONDS = 0.30
REACH_Z = -0.55       # forward, metres from the head (OpenVR: z back)
HAND_Y = -0.35
HAND_X = 0.22

film = "--film" in sys.argv
shift = -0.12 if film else 0.0
out = []


def line(text):
    out.append(text)


def hand_pos(side, x, y, z):
    line(f"{side} pos {x:.4f} {y:.4f} {z + shift:.4f}")


def move(seconds, fn):
    """Call fn(t in 0..1) at every STEP of `seconds`."""
    n = max(1, int(round(seconds / STEP)))
    for i in range(1, n + 1):
        fn(i / n)
        line(f"wait {STEP:.4f}")


def crawl(side):
    sign = 1.0 if side == "right" else -1.0
    x = sign * HAND_X
    hand_pos(side, x, HAND_Y, REACH_Z)
    line(f"{side} grip 1")
    move(PULL_SECONDS, lambda t: hand_pos(side, x, HAND_Y, REACH_Z + PULL_METRES * t))
    line(f"{side} grip 0")
    move(RECOVER_SECONDS, lambda t: hand_pos(side, x, HAND_Y + 0.12 * t * (1 - t) * 4, REACH_Z + PULL_METRES * (1 - t)))


def dive(side):
    # The hand held and pulled up through the water: the swimmer goes down.
    sign = 1.0 if side == "right" else -1.0
    x = sign * HAND_X
    hand_pos(side, x, HAND_Y, REACH_Z + 0.25)
    line(f"{side} grip 1")
    move(PULL_SECONDS, lambda t: hand_pos(side, x, HAND_Y + 0.55 * t, REACH_Z + 0.25))
    line(f"{side} grip 0")
    move(RECOVER_SECONDS, lambda t: hand_pos(side, x, HAND_Y + 0.55 * (1 - t), REACH_Z + 0.25))


def breaststroke():
    # Both hands catch together ahead, sweep apart a little and come back together while pulling to
    # the chest, let go, and reach forward again, hands together.
    for side in ("right", "left"):
        sign = 1.0 if side == "right" else -1.0
        hand_pos(side, sign * 0.10, HAND_Y, REACH_Z)
        line(f"{side} grip 1")

    def pull(t):
        spread = 0.10 + 0.20 * (4 * t * (1 - t))  # apart in the middle, together at both ends
        for side in ("right", "left"):
            sign = 1.0 if side == "right" else -1.0
            hand_pos(side, sign * spread, HAND_Y, REACH_Z + PULL_METRES * t)

    move(PULL_SECONDS, pull)
    for side in ("right", "left"):
        line(f"{side} grip 0")

    def recover(t):
        for side in ("right", "left"):
            sign = 1.0 if side == "right" else -1.0
            hand_pos(side, sign * 0.10, HAND_Y, REACH_Z + PULL_METRES * (1 - t))

    move(RECOVER_SECONDS, recover)


def idle(seconds):
    line(f"wait {seconds}")


line("""# Swimming with the arms (docs/swimming-spec.md; Nadi, 2026-11-27: "go schwimmen mit den armen").
# Generated by tools/gen-swim-script.py (the hands' strokes in steps of a few milliseconds).
# The player is let fall into Lake Rumare (cow Tamriel 1 15, then over the water south of the rocky
# north shore, where water-shore-tester.txt stands) and swims there:
#   water_a .. water_b   hands open and still: the player stays (the game has no drift in water)
#   open_a .. open_b     the hands pulled with the grip open: nothing, a stroke needs the grip
#   crawl_a .. crawl_b   the right hand strokes three times (grip, pull, open, reach out)
#   breast_a .. breast_b both hands stroke twice together, the sweeps apart and together cancel
#   dive_a .. dive_b     the right hand pulled up through the water three times: the player sinks
#                        (read from the marks' "the feet at" z, not asserted by the runner)
#   stick_a .. stick_b   the stick alone, as before: the arms did not take it
# On origin/main dfe4524 the arms do nothing: the crawl and the breaststroke leave the player where it was.
# Run with: python3 tools/hand-script-run.py tools/hand-scripts/swim-arms.txt --headless --no-steamvr --parallel

ini Hands Enabled=1
ini Hands SwimStrokes=1
console-at settle CloseAllMenus
console-at ready cow Tamriel 1 15
console-at placed player.setpos x 5400
console-at placed player.setpos y 64600
console-at placed player.setpos z 300

expect HandScript: finished
expect Swim: the player swims
expect Swim: a hand holds the water
reject HandScript: WARNING
still water_a water_b 40
still open_a open_b 40
moved crawl_a crawl_b 150
moved breast_a breast_b 100
moved stick_a stick_b 150
""")
line("wait 10")
line("mark settle")
line("wait 12")
line("mark ready")
line("wait 20")
line("mark placed")
if film:
    line("head pitch -50")
line("right pos 0.22 -0.35 %.4f" % (REACH_Z + shift))
line("left pos -0.22 -0.35 %.4f" % (REACH_Z + shift))
idle(8)
line("mark water_a")
idle(3)
line("mark water_b")
line("mark open_a")
# Pulled with the grip open: the hands go through the same way, nothing holds the water.
for _ in range(2):
    move(PULL_SECONDS, lambda t: hand_pos("right", HAND_X, HAND_Y, REACH_Z + PULL_METRES * t))
    move(RECOVER_SECONDS, lambda t: hand_pos("right", HAND_X, HAND_Y, REACH_Z + PULL_METRES * (1 - t)))
idle(1.5)
line("mark open_b")
idle(0.5)
line("mark crawl_a")
for _ in range(3):
    crawl("right")
idle(3)
line("mark crawl_b")
idle(0.5)
line("mark breast_a")
for _ in range(2):
    breaststroke()
idle(3)
line("mark breast_b")
idle(0.5)
line("mark dive_a")
for _ in range(3):
    dive("right")
idle(2)
line("mark dive_b")
idle(0.5)
line("mark stick_a")
line("left stick 0 1")
idle(2)
line("left stick 0 0")
idle(1)
line("mark stick_b")
idle(1)
sys.stdout.write("\n".join(l for l in out if l is not None) + "\n")
