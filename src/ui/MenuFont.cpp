// The table has to hold exactly one glyph per printable character, and this is
// the only thing that says so. Get it wrong and every letter past the mistake
// is a different letter - which reads as a font that is subtly scrambled
// rather than as an error, and that is the kind of fault that survives a
// review. Checked at compile time so it cannot.
static_assert(sizeof(kGlyphs) / sizeof(kGlyphs[0]) ==
                  static_cast<UInt32>(kLastGlyph) - static_cast<UInt32>(kFirstGlyph) + 1,
              "the glyph table must cover ' ' through '~' with no gaps");

