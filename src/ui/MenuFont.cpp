bool GlyphPixel(char character, UInt32 x, UInt32 y) {
	if (x >= kGlyphWidth || y >= kGlyphHeight) {
		return false;
	}
	if (character < kFirstGlyph || character > kLastGlyph) {
		return false;
	}

	const UInt32 index = static_cast<UInt32>(character) - static_cast<UInt32>(kFirstGlyph);
	return kGlyphs[index][y][x] == '#';
}

UInt32 TextWidth(const char* text) {
	if (text == nullptr || *text == '\0') {
		return 0;
	}

	UInt32 characters = 0;
	for (const char* at = text; *at != '\0'; ++at) {
		++characters;
	}

	// Every character advances, but the last one's trailing gap is not part of
	// the text - a string measured with it and then right-aligned sits a pixel
	// off, every time, in the same direction.
	return characters * kGlyphAdvance - (kGlyphAdvance - kGlyphWidth);
}

